#!/usr/bin/env python3
"""Refresh engine/ from the aip_products web app: the PRF code, its seeds, and a PRF-only DB.

The Mac app does not re-implement any PRF math. It runs the web app's own page modules,
copied here VERBATIM, against a database cut down to the PRF tables. Run this whenever the
web app's PRF code or data changes (a re-sweep, a new ADM year, edited commission rates),
then rebuild the app with build_app.command (or just run build_app.command --sync).

    python3 sync_engine.py                      # from ~/aip_products (standard library only)
    python3 sync_engine.py --src /path/to/aip_products

What is copied, and the one thing that is not verbatim:

* src/prf*.py page modules and their import closure (config, db, http, prfdata, prfbulk):
  byte-for-byte copies.
* src/prfopt.py is the exception. The pages import only its interval constants, but the
  module imports pandas at load time, which would drag pandas and numpy (~80 MB) into the
  app for six constants. The shim written here carries those constants' source text
  lifted out of the real file by AST, so the numbers cannot be retyped wrong, and
  tests/test_engine.py checks them against the source when the repo is present.
* The DB keeps every table named prf_*, _prf_* or fsa_* from data/catalog_app.db, plus the
  views over them. tests/test_parity.py renders every page from both databases and
  requires identical output, so a table the pages need but this rule misses fails loudly
  rather than rendering an empty map.
"""
from __future__ import annotations

import argparse
import ast
import datetime as _dt
import hashlib
import json
import shutil
import sqlite3
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ENGINE = HERE / "engine"

VERBATIM = [
    "__init__.py",
    "config.py", "db.py", "http.py", "prfdata.py", "prfbulk.py",
    "prfpage.py", "prfvintagepage.py", "prfintervalpage.py", "prfintervals.py", "prfherdpage.py",
    "prfdeck.py", "prfdeckpdf.py", "prfallocpage.py",
]
PRFOPT_NAMES = {"INTERVALS", "MIN_INTERVALS", "MAX_INTERVALS", "STEP_PCT", "MIN_PCT", "MAX_PCT"}
ASSETS = ["d3.v7.min.js", "topojson-client.min.js", "counties-10m.json", "prf_deck_template.pptx"]
SEEDS = ["aip_commission.csv", "commission_by_timezone.csv"]
TABLE_PREFIXES = ("prf_", "_prf_", "fsa_")
DB_NAME = "prf_analytics.db"


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _git(src: Path, *args: str) -> str:
    try:
        return subprocess.run(["git", "-C", str(src), *args], capture_output=True,
                              text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def prfopt_shim(source: str) -> str:
    """The interval constants from prfopt.py, as their original source lines."""
    tree = ast.parse(source)
    parts = []
    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            name = node.target.id
        elif (isinstance(node, ast.Assign) and len(node.targets) == 1
              and isinstance(node.targets[0], ast.Name)):
            name = node.targets[0].id
        else:
            continue
        if name in PRFOPT_NAMES:
            parts.append(ast.get_source_segment(source, node))
    found = {p.split(":")[0].split("=")[0].strip() for p in parts}
    missing = PRFOPT_NAMES - found
    if missing:
        raise SystemExit(f"prfopt.py no longer defines {sorted(missing)} — update sync_engine.py")
    return (
        '"""GENERATED by sync_engine.py — do not edit.\n\n'
        "The interval constants of aip_products/src/prfopt.py, lifted out by AST. The page\n"
        "modules import only these; the real module imports pandas at load time.\n"
        '"""\n'
        "from __future__ import annotations\n\n"
        "from typing import Tuple\n\n"
        + "\n".join(parts) + "\n"
    )


def build_db(src_db: Path, out_db: Path) -> dict[str, int]:
    """Copy the PRF tables (schema, rows, indexes) and the views over them."""
    tmp = out_db.with_suffix(".tmp")
    tmp.unlink(missing_ok=True)
    src_uri = src_db.resolve().as_uri() + "?mode=ro"
    src = sqlite3.connect(src_uri, uri=True)
    objs = src.execute(
        "SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL").fetchall()
    src.close()

    keep = [n for t, n, _, _ in objs if t == "table" and n.startswith(TABLE_PREFIXES)]
    if not keep:
        raise SystemExit(f"no PRF tables in {src_db}")

    dst = sqlite3.connect(tmp.resolve().as_uri(), uri=True)  # uri=True so ATTACH takes a URI
    dst.execute("ATTACH DATABASE ? AS src", (src_uri,))
    counts = {}
    for t, name, tbl, sql in objs:
        if t == "table" and name in keep:
            dst.execute(sql)
            dst.execute(f'INSERT INTO main."{name}" SELECT * FROM src."{name}"')
            counts[name] = dst.execute(f'SELECT COUNT(*) FROM main."{name}"').fetchone()[0]
    for t, name, tbl, sql in objs:
        if t == "index" and tbl in keep:
            dst.execute(sql)
    dst.commit()
    dst.execute("DETACH DATABASE src")
    for t, name, tbl, sql in objs:
        # SQLite accepts a view over a table that does not exist and fails only when the view
        # is read — so every view is created, read once, and dropped if it reads a table
        # this cut left behind (products, SERFF, ...).
        if t == "view":
            dst.execute(sql)
            try:
                counts[name] = dst.execute(f'SELECT COUNT(*) FROM "{name}"').fetchone()[0]
            except sqlite3.OperationalError:
                dst.execute(f'DROP VIEW "{name}"')
    dst.commit()
    dst.execute("VACUUM")
    ok = dst.execute("PRAGMA integrity_check").fetchone()[0]
    dst.close()
    if ok != "ok":
        raise SystemExit(f"integrity_check failed on {tmp}: {ok}")
    tmp.replace(out_db)
    return counts


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--src", default=str(Path.home() / "aip_products"),
                    help="the aip_products repo (default ~/aip_products)")
    ap.add_argument("--db", default=None,
                    help="source DB (default <src>/data/catalog_app.db)")
    args = ap.parse_args()

    src = Path(args.src).expanduser().resolve()
    src_db = Path(args.db).expanduser() if args.db else src / "data" / "catalog_app.db"
    for p in [src / "src" / f for f in VERBATIM + ["prfopt.py"]] + [src / "config.ini", src_db]:
        if not p.exists():
            raise SystemExit(f"missing: {p}")

    (ENGINE / "src").mkdir(parents=True, exist_ok=True)
    (ENGINE / "data" / "assets").mkdir(parents=True, exist_ok=True)
    (ENGINE / "data" / "seed").mkdir(parents=True, exist_ok=True)

    files = {}
    for f in VERBATIM:
        shutil.copy2(src / "src" / f, ENGINE / "src" / f)
        files[f"src/{f}"] = _sha(ENGINE / "src" / f)
    (ENGINE / "src" / "prfopt.py").write_text(prfopt_shim((src / "src" / "prfopt.py").read_text()))
    files["src/prfopt.py"] = "generated from " + _sha(src / "src" / "prfopt.py")
    shutil.copy2(src / "config.ini", ENGINE / "config.ini")
    for f in ASSETS:
        shutil.copy2(src / "data" / "assets" / f, ENGINE / "data" / "assets" / f)
    for f in SEEDS:
        shutil.copy2(src / "data" / "seed" / f, ENGINE / "data" / "seed" / f)
        files[f"data/seed/{f}"] = _sha(ENGINE / "data" / "seed" / f)

    print(f"building {DB_NAME} from {src_db} …")
    counts = build_db(src_db, ENGINE / "data" / DB_NAME)

    dirty = [ln[3:] for ln in _git(src, "status", "--porcelain").splitlines()
             if ln[3:].startswith(("src/prf", "src/config", "src/db", "src/http", "config.ini",
                                   "data/catalog_app.db", "data/seed/", "data/assets/prf_deck"))]
    info = {
        "synced_at": _dt.datetime.now().isoformat(timespec="seconds"),
        "source_repo": str(src),
        "source_commit": _git(src, "rev-parse", "--short", "HEAD"),
        "source_uncommitted": dirty,
        "source_db": str(src_db),
        "source_db_modified": _dt.datetime.fromtimestamp(src_db.stat().st_mtime)
                                .isoformat(timespec="seconds"),
        "db_bytes": (ENGINE / "data" / DB_NAME).stat().st_size,
        "rows": counts,
        "files": files,
    }
    (ENGINE / "SYNC.json").write_text(json.dumps(info, indent=2) + "\n")

    print(f"engine/ synced from {src} @ {info['source_commit'] or '?'}"
          + (f" (+{len(dirty)} uncommitted PRF files)" if dirty else ""))
    print(f"{DB_NAME}: {info['db_bytes'] / 1e6:.1f} MB")
    for name, n in sorted(counts.items()):
        print(f"  {name:24} {n:>10,}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
